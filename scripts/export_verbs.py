"""Export selected verbs from the New Verbs sheet into data/verbs.js.

Usage:
  python3 scripts/export_verbs.py path/to/New-Verbs.xlsx hover click scroll drag@2

Pass no verbs to export every row. When a verb appears more than once (drag,
swipe), the first row wins; write verb@N to take the Nth occurrence instead.
"""
import json
import sys

import openpyxl

FIELDS = {
    "word": "Verb",
    "definition": "Definition",
    "dateComputing": "Date/Computation",
    "computing": "Definition in Computing (if there is a separate one)",
    "signifier": "Visual signifier / affordance",
    "dateOrigin": "Date/Origin",
    "origin": "Root/Origin",
    "history": "Significant Historical Example",
}


def clean(v):
    if v is None:
        return ""
    if isinstance(v, float) and v.is_integer():
        v = int(v)
    return str(v).strip()


def main():
    path, wanted = sys.argv[1], sys.argv[2:]
    ws = openpyxl.load_workbook(path, data_only=True).worksheets[0]
    rows = list(ws.iter_rows(values_only=True))
    head = [clean(h) for h in rows[0]]
    col = {k: head.index(v) for k, v in FIELDS.items()}

    records = [
        {k: clean(r[i]) for k, i in col.items()}
        for r in rows[1:]
        if r[col["word"]] and r[col["definition"]]
    ]

    if wanted:
        out = []
        for w in wanted:
            name, _, n = w.partition("@")
            hits = [x for x in records if x["word"].lower() == name.lower()]
            idx = int(n) - 1 if n else 0
            if idx >= len(hits):
                sys.exit(f"not found: {w}")
            out.append(hits[idx])
    else:
        out = records

    with open("data/verbs.js", "w") as f:
        f.write("// Generated by scripts/export_verbs.py from the New Verbs sheet.\n")
        f.write("window.VERBS = ")
        json.dump(out, f, ensure_ascii=False, indent=2)
        f.write(";\n")
    print(f"wrote {len(out)} verbs")


main()
